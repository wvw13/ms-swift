"""Checkpoint plan shared by training, run and select (steps save strategy)."""
from .config import read,work

def candidate_steps(c):
 t=c['training'];end=t['steps'];every=t['save_steps']
 if type(end)!=int or end<1 or type(every)!=int or every<1:raise ValueError('steps/save_steps must be positive integers')
 # Locked Transformers DefaultFlowCallback saves at max_steps, including off cadence.
 plan=sorted(set(range(every,end+1,every))|{end})
 if 'candidate_steps' not in c:return plan
 chosen=c['candidate_steps']
 if not isinstance(chosen,list) or not chosen:raise ValueError('candidate_steps must be a nonempty list')
 if any(type(x)!=int or x<1 or x>end for x in chosen):raise ValueError('invalid candidate integer/range')
 if len(set(chosen))!=len(chosen):raise ValueError('duplicate candidates')
 if not set(chosen)<=set(plan):raise ValueError('candidate cannot be generated by save schedule')
 return sorted(chosen)

def check_checkpoint(c,step):
 cp=work(c)/'train'/f'checkpoint-{step}'
 required=['adapter_config.json','adapter_model.safetensors','trainer_state.json','optimizer.pt','scheduler.pt']
 world=c['training']['world_size']
 required+=['rng_state.pth'] if world==1 else [f'rng_state_{r}.pth' for r in range(world)]
 for name in required:
  if not (cp/name).is_file() or not (cp/name).stat().st_size:raise ValueError('incomplete checkpoint: '+str(cp/name))
 if read(cp/'trainer_state.json')['global_step']!=step:raise ValueError('checkpoint step mismatch')
 return cp
